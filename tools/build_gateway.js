#!/usr/bin/env node
// Builds supabase/functions/astro-api/index.ts (gateway + /account API) from supabase/functions/_src
// with a provider catalog generated from providers.json (cloud platforms only).
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const src = path.join(root, 'supabase', 'functions', '_src');
const doc = JSON.parse(fs.readFileSync(path.join(root, 'providers.json'), 'utf8'));
const catalog = [];
for (const p of doc.providers) {
  if (p.kind !== 'openai' || p.local || !p.key || !p.base_url || /127\.0\.0\.1|localhost/.test(p.base_url)) continue;
  const base = p.base_url.replace('${NVIDIA_BASE_URL}', 'https://integrate.api.nvidia.com/v1').replace(/\/+$/, '');
  const e = { id: p.id, name: p.name, base, keyName: p.key };
  if (p.requires?.length) e.requires = p.requires;
  if (p.paid) e.paid = true;
  // The gateway asks each platform for its live model list; the catalog keeps only defaults as a fallback.
  if (p.models?.length) e.models = p.models.slice(0, p.discover ? 1 : 4);
  if (p.discover_headers) e.headers = p.discover_headers;
  // OpenRouter app attribution (public app name + site only): https://openrouter.ai/docs/app-attribution
  if (/^https:\/\/openrouter\.ai\//.test(base + '/')) e.headers = { ...(e.headers ?? {}), 'HTTP-Referer': 'https://esoexe.github.io/astro-ai/', 'X-OpenRouter-Title': 'A.S.T.R.O AI', 'X-Title': 'A.S.T.R.O AI', 'X-OpenRouter-Categories': 'general-chat,personal-agent' };
  if (p.discover_suffix) e.suffix = p.discover_suffix;
  if (p.discover_exclude_suffix) e.exclude = p.discover_exclude_suffix;
  if (p.discover_contains) e.contains = p.discover_contains;
  if (p.max_models) e.max = p.max_models;
  if (p.signup) e.signup = p.signup;
  catalog.push(e);
}
const common = fs.readFileSync(path.join(src, 'common.ts'), 'utf8').replace('/*CATALOG*/[]', '[\n' + catalog.map((e) => '  ' + JSON.stringify(e)).join(',\n') + '\n]');
const dir = path.join(root, 'supabase', 'functions', 'astro-api');
fs.mkdirSync(dir, { recursive: true });
const body = `// GENERATED by tools/build_gateway.js from supabase/functions/_src. Do not edit by hand.\n${common}\n${fs.readFileSync(path.join(src, 'account.ts'), 'utf8')}\n${fs.readFileSync(path.join(src, 'api.ts'), 'utf8')}`;
fs.writeFileSync(path.join(dir, 'index.ts'), body);
console.log(`astro-api: ${body.length} bytes, ${catalog.length} providers`);
