#!/usr/bin/env node
// Generates the native Android app's icon set (ui/AppIcons.kt) from the web app's SVG sprite (web/index.html),
// so the web, desktop and Android apps share one icon design. Stroke icons: 24x24, width 1.8, round caps.
//   node tools/android_icons.js          write the Kotlin file
//   node tools/android_icons.js --check  fail when it is out of date
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const OUT = path.join(root, 'android/app/src/main/java/io/github/esoexe/astroai/ui/AppIcons.kt');
const html = fs.readFileSync(path.join(root, 'web/index.html'), 'utf8');

const attrs = (s) => { const o = {}; for (const m of s.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) o[m[1]] = m[2]; return o; };
const n = (v) => Number(v || 0);
const f = (x) => String(Math.round(x * 1000) / 1000);

function toPath(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const cx = n(a.cx); const cy = n(a.cy); const r = n(a.r);
    return `M${f(cx - r)} ${f(cy)}a${f(r)} ${f(r)} 0 1 0 ${f(2 * r)} 0a${f(r)} ${f(r)} 0 1 0 ${f(-2 * r)} 0Z`;
  }
  if (tag === 'rect') {
    const x = n(a.x); const y = n(a.y); const w = n(a.width); const h = n(a.height);
    const r = Math.min(n(a.rx || a.ry), w / 2, h / 2);
    if (!r) return `M${f(x)} ${f(y)}h${f(w)}v${f(h)}h${f(-w)}Z`;
    return `M${f(x + r)} ${f(y)}h${f(w - 2 * r)}a${f(r)} ${f(r)} 0 0 1 ${f(r)} ${f(r)}v${f(h - 2 * r)}a${f(r)} ${f(r)} 0 0 1 ${f(-r)} ${f(r)}h${f(-(w - 2 * r))}a${f(r)} ${f(r)} 0 0 1 ${f(-r)} ${f(-r)}v${f(-(h - 2 * r))}a${f(r)} ${f(r)} 0 0 1 ${f(r)} ${f(-r)}Z`;
  }
  if (tag === 'line') return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
  if (tag === 'polyline' || tag === 'polygon') { const p = a.points.trim().split(/[\s,]+/); let d = `M${p[0]} ${p[1]}`; for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`; return tag === 'polygon' ? `${d}Z` : d; }
  throw new Error(`Unsupported SVG element <${tag}>`);
}

function build() {
  const icons = [];
  for (const m of html.matchAll(/<symbol id="i-([a-z0-9-]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
    const parts = [];
    for (const e of m[2].matchAll(/<(path|circle|rect|line|polyline|polygon)\b([^>]*?)\/?>/g)) {
      const a = attrs(e[2]);
      const fill = a.fill === 'currentColor' ? 1 : a.fill && a.fill.startsWith('url(') ? 2 : 0;   // 0 stroke, 1 filled, 2 brand gradient
      parts.push([fill, toPath(e[1], a)]);
    }
    icons.push([m[1], parts]);
  }
  if (icons.length < 60) throw new Error(`Only ${icons.length} icons found in web/index.html`);
  const camel = (s) => s.replace(/-([a-z0-9])/g, (_x, c) => c.toUpperCase());
  const lines = icons.map(([id, parts]) => `    val ${camel(id).replace(/^(\d)/, '_$1')}: ImageVector by lazy { icon("${id}", ${parts.map(([fl, d]) => `${fl} to "${d}"`).join(', ')}) }`);
  return `// GENERATED by tools/android_icons.js from the web app's SVG sprite (web/index.html). Do not edit by hand.
package io.github.esoexe.astroai.ui

import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp
import androidx.compose.ui.geometry.Offset

/** The A.S.T.R.O AI icon set: ${icons.length} icons, 24x24 strokes that take the content colour (Icon tint). */
object AppIcons {
    private val brand = Brush.linearGradient(listOf(Color(0xFFF7C59F), Color(0xFFF3A679), Color(0xFFE07A4F)), Offset(0f, 0f), Offset(24f, 24f))

    /** kind: 0 = stroke, 1 = filled (and stroked), 2 = brand gradient fill. */
    private fun icon(name: String, vararg parts: Pair<Int, String>): ImageVector {
        val b = ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
        for ((kind, d) in parts) {
            val nodes = PathParser().parsePathString(d).toNodes()
            when (kind) {
                2 -> b.addPath(nodes, fill = brand)
                1 -> b.addPath(nodes, fill = SolidColor(Color.Black), stroke = SolidColor(Color.Black), strokeLineWidth = 1.8f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)
                else -> b.addPath(nodes, stroke = SolidColor(Color.Black), strokeLineWidth = 1.8f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)
            }
        }
        return b.build()
    }

${lines.join('\n')}
}
`;
}

const text = build();
if (process.argv.includes('--check')) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) { console.error('AppIcons.kt is stale: run node tools/android_icons.js'); process.exit(1); }
  console.log('icons OK');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`AppIcons.kt: ${(text.match(/by lazy/g) || []).length} icons`);
}
