// gen_entities.cpp: builds packtools/html_entities.h, the HTML5 named character references, so pyrt's
// html_unescape() decodes them the way Python's html.unescape() does (its html.entities.html5 table is the same
// 2231 names, with and without the trailing ';').
//
//   curl -sfL https://html.spec.whatwg.org/entities.json -o /tmp/entities.json
//   g++ -std=c++20 -O1 tools/html/gen_entities.cpp -o /tmp/gen_entities && /tmp/gen_entities /tmp/entities.json packtools/html_entities.h
//
// entities.json is part of the HTML Living Standard, (c) WHATWG (Apple, Google, Mozilla, Microsoft), under the
// Creative Commons Attribution 4.0 International License (see THIRD-PARTY-NOTICES.md).
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc != 3) { std::cerr << "usage: gen_entities entities.json OUT.h\n"; return 2; }
    std::ifstream in(argv[1]); std::stringstream ss; ss << in.rdbuf(); const std::string j = ss.str();
    if (j.empty()) { std::cerr << "cannot read " << argv[1] << "\n"; return 1; }
    struct E { std::string name; std::vector<uint32_t> cps; };
    std::vector<E> all;
    // every entry reads: "&name": { "codepoints": [n, ...], "characters": "..." }
    std::size_t k = 0;
    while ((k = j.find("\"&", k)) != std::string::npos) {
        const std::size_t e = j.find('"', k + 2); if (e == std::string::npos) break;
        E x; x.name = j.substr(k + 2, e - k - 2);
        const std::size_t cp = j.find("\"codepoints\"", e), lb = j.find('[', cp), rb = j.find(']', lb);
        if (cp == std::string::npos || lb == std::string::npos || rb == std::string::npos) { std::cerr << "bad entry " << x.name << "\n"; return 1; }
        std::stringstream nums(j.substr(lb + 1, rb - lb - 1)); std::string t;
        while (std::getline(nums, t, ',')) x.cps.push_back(static_cast<uint32_t>(std::stoul(t)));
        if (x.cps.empty() || x.cps.size() > 2) { std::cerr << "unexpected code point count for " << x.name << "\n"; return 1; }
        all.push_back(x); k = rb;
    }
    std::sort(all.begin(), all.end(), [](const E& a, const E& b) { return a.name < b.name; });
    std::ofstream out(argv[2]);
    out << "// Generated by tools/html/gen_entities.cpp from the WHATWG HTML Standard's entities.json ((c) WHATWG,\n"
           "// CC BY 4.0). Do not edit: re-run the generator. Names are without the leading '&', sorted bytewise.\n"
           "#pragma once\n#include <cstdint>\nnamespace pyrt::html5 {\nstruct Ent { const char* name; uint32_t a, b; };   // b = 0: one code point\n"
           "inline constexpr Ent ENTITIES[] = {\n";
    int n = 0;
    for (const auto& x : all) {
        char b[96]; std::snprintf(b, sizeof b, "{\"%s\",0x%x,0x%x},", x.name.c_str(), x.cps[0], x.cps.size() > 1 ? x.cps[1] : 0u);
        out << b; if (++n % 5 == 0) out << "\n";
    }
    out << "\n};\n}  // namespace pyrt::html5\n";
    std::cerr << all.size() << " entities\n";
    return all.size() == 2231 ? 0 : 1;
}
