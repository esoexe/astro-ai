// gen_cp932.cpp - writes packtools/cp932_table.h from Microsoft's CP932.TXT
// (https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WINDOWS/CP932.TXT). The table holds the double-byte codes;
// single bytes and the user-defined area (F040-F9FC -> U+E000..) follow CPython's cp932 decoder rules in code.
// Build: g++ -std=c++20 -O2 tools/cp932/gen_cp932.cpp -o /tmp/gen_cp932 && /tmp/gen_cp932 CP932.TXT packtools/cp932_table.h
#include <cctype>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>
static int lead_index(unsigned c) { return c >= 0x81 && c <= 0x9F ? static_cast<int>(c - 0x81) : c >= 0xE0 && c <= 0xFC ? static_cast<int>(c - 0xE0 + 31) : -1; }
int main(int argc, char** argv) {
    if (argc != 3) { std::fprintf(stderr, "usage: gen_cp932 <CP932.TXT> <out.h>\n"); return 2; }
    std::ifstream in(argv[1]); if (!in) { std::fprintf(stderr, "cannot read %s\n", argv[1]); return 2; }
    std::vector<std::vector<unsigned>> tab(60, std::vector<unsigned>(189, 0));
    std::string line; int n = 0;
    while (std::getline(in, line)) {
        if (line.size() < 13 || line.compare(0, 2, "0x") != 0) continue;
        std::size_t k = 2; while (k < line.size() && std::isxdigit(static_cast<unsigned char>(line[k]))) ++k;
        if (k - 2 != 4) continue;                      // double-byte codes only
        const unsigned code = static_cast<unsigned>(std::strtoul(line.substr(2, 4).c_str(), nullptr, 16));
        std::size_t u = line.find("0x", k); if (u == std::string::npos) continue;   // an unmapped code has no second column
        const std::size_t ue = line.find_first_not_of("0123456789abcdefABCDEF", u + 2);
        if (ue == u + 2) continue;
        const unsigned uni = static_cast<unsigned>(std::strtoul(line.substr(u + 2, ue - u - 2).c_str(), nullptr, 16));
        const unsigned lead = code >> 8, tr = code & 0xFF; const int li = lead_index(lead);
        if (li < 0 || tr < 0x40 || tr > 0xFC) { std::fprintf(stderr, "unexpected code 0x%04X\n", code); return 1; }
        tab[static_cast<std::size_t>(li)][tr - 0x40] = uni; ++n;
    }
    std::ostringstream o;
    o << "// cp932_table.h - generated by tools/cp932/gen_cp932.cpp from Microsoft's CP932.TXT (via unicode.org MAPPINGS; see\n"
      << "// THIRD-PARTY-NOTICES.md). Double-byte cp932 codes: CP932_DBCS[lead index][trail - 0x40], 0 = unmapped.\n"
      << "// Lead index: 0x81..0x9F -> 0..30, 0xE0..0xFC -> 31..59. " << n << " codes.\n#pragma once\n#include <cstdint>\nnamespace pyrt::cp932 {\n"
      << "inline constexpr uint16_t DBCS[60][189] = {\n";
    for (std::size_t r = 0; r < 60; ++r) {
        o << "{"; for (std::size_t c = 0; c < 189; ++c) { if (c) o << ","; o << tab[r][c]; } o << "}" << (r + 1 < 60 ? ",\n" : "};\n");
    }
    o << "inline int lead_index(unsigned c) { return c >= 0x81 && c <= 0x9F ? static_cast<int>(c - 0x81) : c >= 0xE0 && c <= 0xFC ? static_cast<int>(c - 0xE0 + 31) : -1; }\n"
      << "}  // namespace pyrt::cp932\n";
    std::ofstream out(argv[2], std::ios::binary); out << o.str();
    std::printf("codes %d bytes %zu\n", n, o.str().size());
    return 0;
}
