// gen_unicode.cpp: builds packtools/unicode_data.h from the Unicode Character Database, so the pack tools can do what
// Python's unicodedata does (category, combining, normalize NFC/NFD/NFKC/NFKD) without ICU and without Python.
//
//   cd tools/unicode
//   curl -sfLO https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt
//   curl -sfLO https://www.unicode.org/Public/15.1.0/ucd/CompositionExclusions.txt
//   g++ -std=c++20 -O1 gen_unicode.cpp -o /tmp/gen_unicode && /tmp/gen_unicode . ../../packtools/unicode_data.h
//
// Unicode 15.1.0 is the version Python 3.13 ships (3.12 has 15.0.0; the two differ only in new CJK ideographs, which have
// no decompositions). The data files are (c) Unicode, Inc., under the Unicode License v3 (see THIRD-PARTY-NOTICES.md).
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

static const char* CATS[] = {"Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
                             "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co"};
static int cat_index(const std::string& c) {
    for (int k = 0; k < 30; ++k) if (c == CATS[k]) return k;
    std::cerr << "unknown category " << c << "\n";
    std::exit(1);
}
static std::vector<std::string> split(const std::string& s, char sep) {
    std::vector<std::string> o; std::string cur;
    for (char ch : s) { if (ch == sep) { o.push_back(cur); cur.clear(); } else cur += ch; }
    o.push_back(cur);
    return o;
}

int main(int argc, char** argv) {
    if (argc != 3) { std::cerr << "usage: gen_unicode UCD_DIR OUT.h\n"; return 2; }
    const std::string dir = argv[1];
    std::ifstream ud(dir + "/UnicodeData.txt");
    if (!ud) { std::cerr << "no UnicodeData.txt in " << dir << "\n"; return 1; }
    std::vector<uint8_t> cat(0x110000, 0), ccc(0x110000, 0);
    struct D { bool compat; std::vector<uint32_t> to; };
    std::map<uint32_t, D> dec;
    std::string line; uint32_t range_first = 0; bool in_range = false;
    while (std::getline(ud, line)) {
        if (line.empty()) continue;
        const auto f = split(line, ';');
        const uint32_t cp = static_cast<uint32_t>(std::stoul(f[0], nullptr, 16));
        const int c = cat_index(f[2]);
        if (f[1].find(", First>") != std::string::npos) { range_first = cp; in_range = true; continue; }
        if (in_range && f[1].find(", Last>") != std::string::npos) {
            for (uint32_t x = range_first; x <= cp; ++x) { cat[x] = static_cast<uint8_t>(c); ccc[x] = static_cast<uint8_t>(std::stoi(f[3])); }
            in_range = false; continue;
        }
        cat[cp] = static_cast<uint8_t>(c);
        ccc[cp] = static_cast<uint8_t>(std::stoi(f[3]));
        if (!f[5].empty()) {
            D d{false, {}};
            std::istringstream ss(f[5]); std::string tok;
            while (ss >> tok) { if (tok[0] == '<') { d.compat = true; continue; } d.to.push_back(static_cast<uint32_t>(std::stoul(tok, nullptr, 16))); }
            dec[cp] = d;
        }
    }
    std::vector<uint32_t> excl;
    std::ifstream ce(dir + "/CompositionExclusions.txt");
    if (!ce) { std::cerr << "no CompositionExclusions.txt in " << dir << "\n"; return 1; }
    while (std::getline(ce, line)) {
        const auto h = line.find('#'); if (h != std::string::npos) line = line.substr(0, h);
        std::istringstream ss(line); std::string tok;
        if (ss >> tok) excl.push_back(static_cast<uint32_t>(std::stoul(tok, nullptr, 16)));
    }
    std::ofstream o(argv[2]);
    o << "// Generated by tools/unicode/gen_unicode.cpp from the Unicode Character Database 15.1.0 (UnicodeData.txt,\n"
         "// CompositionExclusions.txt; (c) Unicode, Inc., Unicode License v3). Do not edit: re-run the generator.\n#pragma once\n#include <cstdint>\n"
         "namespace pyrt::uni::data {\ninline constexpr const char* VERSION = \"15.1.0\";\n"
         "inline constexpr const char* CAT_NAMES[30] = {";
    for (int k = 0; k < 30; ++k) o << (k ? ", " : "") << '"' << CATS[k] << '"';
    o << "};\n// general category: range starts (the category holds until the next start)\nstruct CatRun { uint32_t lo; uint8_t cat; };\ninline constexpr CatRun CAT[] = {\n";
    int n = 0;
    for (uint32_t x = 0; x < 0x110000; ++x) if (x == 0 || cat[x] != cat[x - 1]) { o << "{0x" << std::hex << x << std::dec << "," << int(cat[x]) << "},"; if (++n % 10 == 0) o << "\n"; }
    o << "};\n// canonical combining class, nonzero runs\nstruct CccRun { uint32_t lo, hi; uint8_t ccc; };\ninline constexpr CccRun CCC[] = {\n";
    n = 0;
    for (uint32_t x = 0; x < 0x110000; ++x) {
        if (!ccc[x] || (x && ccc[x] == ccc[x - 1])) continue;
        uint32_t y = x; while (y + 1 < 0x110000 && ccc[y + 1] == ccc[x]) ++y;
        o << "{0x" << std::hex << x << ",0x" << y << std::dec << "," << int(ccc[x]) << "},"; if (++n % 8 == 0) o << "\n";
    }
    o << "};\n// one-level decompositions (Hangul syllables are algorithmic): info = offset into POOL | len << 20 | compat << 25\n"
         "struct Dec { uint32_t cp, info; };\ninline constexpr Dec DEC[] = {\n";
    std::vector<uint32_t> pool; n = 0;
    for (const auto& [cp, d] : dec) {
        const uint32_t info = static_cast<uint32_t>(pool.size()) | (static_cast<uint32_t>(d.to.size()) << 20) | (d.compat ? 1u << 25 : 0u);
        for (uint32_t t : d.to) pool.push_back(t);
        o << "{0x" << std::hex << cp << ",0x" << info << std::dec << "},"; if (++n % 8 == 0) o << "\n";
    }
    o << "};\ninline constexpr uint32_t POOL[] = {\n";
    n = 0;
    for (uint32_t t : pool) { o << "0x" << std::hex << t << std::dec << ","; if (++n % 12 == 0) o << "\n"; }
    o << "};\n// CompositionExclusions.txt (singletons and non-starter decompositions are worked out at run time)\ninline constexpr uint32_t EXCL[] = {\n";
    n = 0;
    for (uint32_t t : excl) { o << "0x" << std::hex << t << std::dec << ","; if (++n % 12 == 0) o << "\n"; }
    o << "};\n}  // namespace pyrt::uni::data\n";
    std::cerr << "decompositions " << dec.size() << ", pool " << pool.size() << ", exclusions " << excl.size() << "\n";
    return 0;
}
