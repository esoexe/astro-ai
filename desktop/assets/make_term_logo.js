// Rasterises the small icon for the terminal app's welcome card -> cli/logo.h (RGBA pixels, drawn with half-blocks).
//   NODE_PATH=/tmp/pw/node_modules node desktop/assets/make_term_logo.js [size=20]
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const N = Number(process.argv[2] || 20);
(async () => {
  // A bold, tile-less version of the mark: thick orbits survive a ${N}px raster.
  const R = 46, r = 15, sw = Number(process.argv[3] || 6);
  const arc = (rot, front) => { const a = rot * Math.PI / 180, c = Math.cos(a), s2 = Math.sin(a);
    const P = (t) => [50 + R * Math.cos(t) * c - r * Math.sin(t) * s2, 50 + R * Math.cos(t) * s2 + r * Math.sin(t) * c].map((v) => v.toFixed(2));
    const [x0, y0] = P(front ? Math.PI : 0), [x1, y1] = P(front ? 0 : Math.PI);
    return `<path d="M${x0} ${y0} A${R} ${r} ${rot} 0 ${front ? 0 : 0} ${x1} ${y1}" fill="none" stroke="${front ? 'url(#ring)' : '#b9714f'}" stroke-width="${sw}" stroke-linecap="round"/>`; };
  const sat = (rot, t) => { const a = rot * Math.PI / 180; const x = R * Math.cos(t), y = r * Math.sin(t); return `<circle cx="${(50 + x * Math.cos(a) - y * Math.sin(a)).toFixed(2)}" cy="${(50 + x * Math.sin(a) + y * Math.cos(a)).toFixed(2)}" r="5.2" fill="#fff4ea"/>`; };
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><defs>
    <radialGradient id="core" cx="38%" cy="32%" r="78%"><stop offset="0" stop-color="#ffe6d3"/><stop offset=".45" stop-color="#f7b78f"/><stop offset="1" stop-color="#e2774c"/></radialGradient>
    <linearGradient id="ring" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#ffd2b5"/><stop offset=".5" stop-color="#f3a679"/><stop offset="1" stop-color="#ef9466"/></linearGradient></defs>
    ${[0, 60, -60].map((d) => arc(d, false)).join('')}<circle cx="50" cy="50" r="19" fill="url(#core)"/>${[0, 60, -60].map((d) => arc(d, true)).join('')}
    ${sat(0, 3.6)}${sat(60, -0.5)}${sat(-60, 2.5)}</svg>`;
  fs.writeFileSync(path.join(__dirname, 'term-mark.svg'), svg);
  const b = await chromium.launch();
  try {
    const p = await b.newPage();
    await p.setContent('<canvas id=c></canvas>');
    const px = await p.evaluate(async ({ svg, N }) => {
      const img = new Image(); img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svg)));
      await img.decode();
      const c = document.getElementById('c'); c.width = N; c.height = N;
      const g = c.getContext('2d'); g.imageSmoothingQuality = 'high'; g.drawImage(img, 0, 0, N, N);
      return Array.from(g.getImageData(0, 0, N, N).data);
    }, { svg, N });
    const v = [];
    for (let i = 0; i < px.length; i += 4) v.push('0x' + (((px[i + 3] << 24) | (px[i] << 16) | (px[i + 1] << 8) | px[i + 2]) >>> 0).toString(16).padStart(8, '0'));
    let out = `// Generated by desktop/assets/make_term_logo.js from icon-small.svg: ${N}x${N} pixels, 0xAARRGGBB.\n#pragma once\n#include <cstdint>\nstatic const int LOGO_N = ${N};\nstatic const uint32_t LOGO[${N * N}] = {\n`;
    for (let r = 0; r < N; r++) out += '    ' + v.slice(r * N, r * N + N).join(', ') + ',\n';
    fs.writeFileSync(path.join(__dirname, '../../cli/logo.h'), out + '};\n');
    console.log('wrote cli/logo.h', N + 'x' + N);
  } finally { await b.close(); }
})();
