#!/usr/bin/env bash
# console-mod/override: the TestOverridePy and TestReachability cases of console-skill/tests/test_mod.py, plus exact
# output, the generated module checked with g++ against mock PS2Recomp headers, every input error, the ELF checks,
# the Astro library's .txt templates, and the --out guard.
source "$(dirname "$0")/lib.sh"
LIBSKILL="$(cd "$(dirname "$0")/../.." && pwd)/library/plugins/astro-console/skills/console-mod"
MOCK="$FIX/ps2mock"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
cd "$TMP" || exit 1
node "$FIX/mkmodelf.js" standard SLUS_999.99
node "$FIX/mkmodelf.js" nosections plain.elf
CRC=$(node -e 'console.log(require("zlib").crc32(require("fs").readFileSync(process.argv[1])).toString(16).toUpperCase().padStart(8,"0"))' SLUS_999.99)
OV=(--skill-dir "$LIBSKILL" console-mod/override)
TODAY=$(date +%F)
mkdir -p PS2Recomp/ps2xRuntime/include
printf '#pragma once\n#define PS2_SYSCALL_LIST(X) \\\n    X(FlushCache) \\\n    X(_ResetEE)\n\n#define PS2_STUB_LIST(X) \\\n    X(ret0) \\\n    X(sceCdRead)\n' > PS2Recomp/ps2xRuntime/include/ps2_call_list.h
GOLD="$TMP/console/patches/gold.cpp"
newg() { run "${OV[@]}" new --name "Gold rifle" --elf SLUS_999.99 --out "$GOLD" "$@"; }
compiles() {   # g++ -fsyntax-only -Werror against the mock headers, like compile_ok
    command -v g++ >/dev/null || { ok; return; }
    if g++ -std=c++20 -fsyntax-only -Wall -Wextra -Werror -I "$MOCK" -x c++ "$1" 2>/tmp/ov_cxx; then ok; else bad "$2: $(head -5 /tmp/ov_cxx)"; fi
}

# ---- test_keys
run "${OV[@]}" keys SLUS_999.99
eq "$CODE" 0 "keys exit"
eq "$OUT" "PS2_REGISTER_GAME_OVERRIDE(\"your mod\", \"SLUS_999.99\", 0x00100000u, 0x${CRC}u, &applyOverride)
  file name SLUS_999.99, entry 0x00100000, CRC-32 0x${CRC} (standard CRC-32 of the whole ELF, not the PCSX2 CRC)" "keys text"
run "${OV[@]}" keys "$TMP/nope"
eq "$CODE" 2 "keys missing"; eq "$ERR" "override: error: ELF not found: $TMP/nope" "missing ELF message"
run "${OV[@]}" keys "$TMP"
eq "$ERR" "override: error: ELF not found: $TMP" "a folder is not an ELF"
run "${OV[@]}" keys plain.elf
has "$OUT" '"plain.elf", 0x00100000u' "section-less ELF"
printf 'hello' > tiny.bin; run "${OV[@]}" keys tiny.bin
eq "$ERR" "override: error: tiny.bin is not an ELF file" "short file"
cp SLUS_999.99 b64.elf; perl -e 'open F,"+<","b64.elf"; seek F,4,0; print F chr(2); close F'
run "${OV[@]}" keys b64.elf; eq "$ERR" "override: error: b64.elf is not a 32-bit little-endian ELF (PS2 EE ELFs are)" "64-bit"
cp SLUS_999.99 x86.elf; perl -e 'open F,"+<","x86.elf"; seek F,18,0; print F pack("v",3); close F'
run "${OV[@]}" keys x86.elf; eq "$ERR" "override: error: x86.elf is not a MIPS ELF (machine 3, the PS2 EE is 8)" "machine"
head -c 80 SLUS_999.99 > cut.elf; run "${OV[@]}" keys cut.elf
eq "$ERR" "override: error: cut.elf is truncated or has a bad program header table" "phdrs cut"
head -c 130 SLUS_999.99 > cut2.elf; run "${OV[@]}" keys cut2.elf
eq "$ERR" "override: error: cut2.elf is truncated: segment 0 runs past the end of the file" "segment cut"
eq "$CODE" 2 "segment cut exit"

# ---- test_new_bind_replace_wrap
newg --bind 0x00100018=sceCdRead --replace 0x00100000=gold_damage --wrap 0x0010001C=gold_ammo --repo PS2Recomp
eq "$CODE" 0 "new exit"
eq "$OUT" "wrote $GOLD  (keys: SLUS_999.99, entry 0x00100000, CRC-32 0x${CRC})
  install: wrote $TMP/console/patches/console_mods.cmake; add once at the end of ps2xRuntime/CMakeLists.txt: include(\"$TMP/console/patches/console_mods.cmake\" OPTIONAL)
  (it adds the .cpp files to the ps2EntryRunner executable itself: inside the static ps2_runtime
  library the linker would drop the self-registration)
  then: cmake --build out/build --config Debug  (incremental, never clean)" "new stdout"
TXT=$(cat "$GOLD")
has "$TXT" "PS2_REGISTER_GAME_OVERRIDE(\"Gold rifle\", \"SLUS_999.99\", 0x00100000u, 0x${CRC}u, &applyOverride)" "register line"
has "$TXT" 'ps2_game_overrides::bindAddressHandler(runtime, 0x00100018u, "sceCdRead");' "bind"
has "$TXT" "void gold_damage(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)" "replace fn"
has "$TXT" "getRegU32(ctx, 4)" "a0"; has "$TXT" "ctx->pc = getRegU32(ctx, 31);" "return"
has "$TXT" "runtime.replaceFunction(0x00100000u, &gold_damage)" "replace call"
has "$TXT" "g_original_gold_ammo = current;" "wrap keeps original"
has "$TXT" "if (ctx->pc != returnAddress)" "wrap pause check"
has "$TXT" "namespace console_mod_gold_rifle" "namespace"
has "$TXT" "// Mod: Gold rifle
// Generated by console-mod override.py new on $TODAY for SLUS_999.99 (676 bytes).
//   bind    0x00100018 -> runtime handler sceCdRead
//   replace 0x00100000 -> gold_damage()
//   wrap    0x0010001C -> gold_ammo() around the game's function
// Replacing a function affects calls that go through the runtime's function table (jal,
// jalr and register jumps). A j tail jump to a known function is emitted as a direct C++
// call and skips it: if a target is reached only by j, hook the caller one level up.
//   0x00100018: reached by 1 jal and 0 j instruction(s) in the ELF
//   0x00100000: reached by 0 jal and 0 j instruction(s) in the ELF
//   0x0010001C: reached by 0 jal and 0 j instruction(s) in the ELF
#include \"game_overrides.h\"" "notes block"
has "$TXT" "        std::cerr << \"[console-mod] Gold rifle: no recompiled function at 0x0010001C to wrap\" << std::endl;
    }
}

// Keys:" "apply body ends without blank lines"
CODEONLY=$(grep -v '^[[:space:]]*//' "$GOLD")
hasnt "$CODEONLY" "Runtime::OverrideFunction" "no fake API"; hasnt "$CODEONLY" "Runtime.h" "no Runtime.h"
eq "$(grep -cE '@[A-Z_]+@' "$GOLD")" 0 "no unfilled fields"
eq "$(cat console/patches/console_mods.cmake)" "$(cat "$LIBSKILL/templates/console_mods.cmake.txt")" "cmake copied from the template"
compiles "$GOLD" "bind/replace/wrap module compiles"
eq "$(tail -c 1 "$GOLD" | od -An -c | tr -d ' ')" '\n' "ends with a newline"

# ---- test_new_compiles_against_mock_headers (ret0 is generic: no warning)
newg --bind 0x00100018=ret0 --replace 0x00100000=gold_damage --wrap 0x0010001C=gold_ammo --force
eq "$CODE" 0 "generic handler: no warning"
eq "$(echo "$OUT" | sed -n 2p)" "  install: console_mods.cmake already next to it" "cmake already there"
compiles "$GOLD" "ret0 module compiles"
newg --replace 0x00100000=only_me --force
compiles "$GOLD" "replace-only module compiles"
newg --bind 0x00100018=ret1 --force
compiles "$GOLD" "bind-only module compiles"

# ---- test_handler_alias_and_unknown
newg --bind 0x00100018=ResetEE --repo PS2Recomp --force
eq "$CODE" 0 "alias exit"; has "$(cat "$GOLD")" '"_ResetEE"' "alias adds the underscore"
newg --bind 0x00100018=_FlushCache --repo PS2Recomp --force
has "$(cat "$GOLD")" '"FlushCache");' "alias drops the underscore"
newg --bind 0x00100018=NotAHandler --repo PS2Recomp --force
eq "$CODE" 2 "unknown handler"
eq "$ERR" "override: error: --bind handler 'NotAHandler' is not in PS2_SYSCALL_LIST or PS2_STUB_LIST of PS2Recomp" "unknown handler message"
newg --bind 0x00100018=ret0 --repo "$TMP/none" --force
eq "$ERR" "override: error: no ps2xRuntime/include/ps2_call_list.h under $TMP/none (is that a PS2Recomp checkout?)" "not a checkout"
mkdir -p empty/ps2xRuntime/include; printf '#define PS2_OTHER_LIST(X) X(Foo)\n' > empty/ps2xRuntime/include/ps2_call_list.h
newg --bind 0x00100018=Foo --repo empty --force
eq "$ERR" "override: error: found no X(Name) entries in empty/ps2xRuntime/include/ps2_call_list.h" "no entries (other lists ignored)"

# ---- test_unchecked_handler_warns
newg --bind 0x00100018=SomethingElse --force
eq "$CODE" 1 "unchecked: exit 1"
eq "$(echo "$OUT" | sed -n 2p)" "  warning: handler 'SomethingElse' not checked: pass --repo <PS2Recomp> to verify it exists" "unchecked warning"
[ -f "$GOLD" ] && ok || bad "written despite warnings"

# ---- test_bad_arguments: exit 2, the message, nothing written
rm -rf console
badarg() { local want="$1"; shift; newg "$@"; eq "$CODE" 2 "bad: $*"; eq "$ERR" "override: error: $want" "message: $*"; }
badarg "give at least one --bind, --replace or --wrap (see --help)"
badarg "--replace needs 0xADDR=name, got '00100000'" --replace 00100000
badarg "--replace address 0x00100002 is not 4-byte aligned (functions start on a word)" --replace 0x00100002=f
badarg "--replace name '9bad' is not a C++ identifier" --replace 0x00100000=9bad
badarg "'class' is a reserved name, pick another function name" --replace 0x00100000=class
badarg "'applyOverride' is a reserved name, pick another function name" --wrap 0x00100000=applyOverride
badarg "function name 'f' is used twice" --replace 0x00100000=f --wrap 0x00100004=f
badarg "address used twice: 0x00100000" --replace 0x00100000=f --wrap 0x00100000=g
badarg "address used twice: 0x00100000, 0x00100004" --bind 0x00100004=ret0 --bind 0x00100000=ret0 --replace 0x00100004=f --wrap 0x00100000=g
badarg "--replace address is not hex: 'zz'" --replace zz=f
badarg "--bind address is not hex: ''" --bind =ret0
badarg "--wrap address out of range: '-0x4'" --wrap=-0x4=f
badarg "--wrap address out of range: '0x100000000'" --wrap 0x100000000=f
badarg "--wrap address out of range: '0x1FFFFFFFFFFFFFFFFFFFF'" --wrap 0x1FFFFFFFFFFFFFFFFFFFF=f
badarg "--bind name 'a-b' is not a C++ identifier" --bind 0x00100000=a-b
badarg "--replace name 'café' is not a C++ identifier" --replace 0x00100000=café
[ -e console ] && bad "bad input wrote something" || ok
newg --replace " 0x0010_0000 = spaced " --force
eq "$CODE" 0 "int(x, 16) rules: spaces and underscores"; has "$(cat "$GOLD")" "void spaced(" "stripped name"
newg --replace 100004=nohex --force
eq "$CODE" 0 "no 0x prefix"; has "$(cat "$GOLD")" "0x00100004u, &nohex" "bare hex"
newg --bind 0x00100018=nope; eq "$ERR" "override: error: $GOLD exists: pass --force to overwrite it (it may hold your own code)" "--force needed"

# ---- test_address_warnings
printf 'Name,Start,End,Size\nsub_00100000,0x00100000,0x00100030,48\n' > map.csv
newg --replace 0x00200000=f --map map.csv --force
eq "$CODE" 1 "address warnings exit"
eq "$(echo "$OUT" | sed -n 2,3p)" "  warning: 0x00200000 is not inside an executable segment of SLUS_999.99
  warning: 0x00200000 is not a function start in the Ghidra map" "address warnings"
printf 'Name,Start\r\nf,0X00100004\r\ng, 0x0010_0008 \r\nh,zz\nbad\n' > map2.csv
newg --replace 0x00100004=f --wrap 0x00100008=g --map map2.csv --force
eq "$CODE" 0 "map: 0X, spaces, underscores, CRLF"
newg --replace 0x00100004=f --map nomap.csv --force
eq "$ERR" "override: error: Ghidra map not found: nomap.csv" "missing map"

# ---- reachability: jal yes, j tail jump no
newg --wrap 0x00100024=w --force
eq "$CODE" 1 "tail jump: exit 1"
eq "$(echo "$OUT" | sed -n 2p)" "  warning: 0x00100024 is the target of 1 j tail jump(s) (0x00100038): PS2Recomp emits those as direct C++ calls that skip the function table, so your function does not run on those paths; nothing reaches it with jal: pick the caller one level up" "tail jump warning"
has "$(cat "$GOLD")" "0x00100024: reached by 0 jal and 1 j instruction(s)" "j counted"
newg --replace 0x00100018=r --force
eq "$CODE" 0 "jal target: exit 0"; has "$(cat "$GOLD")" "reached by 1 jal and 0 j" "jal counted"
run "${OV[@]}" new --name w --elf plain.elf --wrap 0x00100024=w --out "$TMP/p/w.cpp"
has "$OUT" "(0x00100038)" "section-less ELF scans too"

# ---- test_refuses_runner_and_existing
run "${OV[@]}" new --name x --elf SLUS_999.99 --replace 0x00100000=f --out "$TMP/x/ps2xRuntime/src/runner/m.cpp"
eq "$CODE" 2 "runner refused"; eq "$ERR" "override: error: refusing to write into ps2xRuntime/src/runner/ (generated code): use console/patches/" "runner message"
run "${OV[@]}" new --name x --elf SLUS_999.99 --replace 0x00100000=f --out "$TMP/x/ps2xRuntime/src/runner"
eq "$CODE" 2 "the runner folder itself"
run "${OV[@]}" new --name x --elf SLUS_999.99 --replace 0x00100000=f --out "$TMP/m.h"
eq "$ERR" "override: error: the output must be a .cpp file: $TMP/m.h" ".cpp only"
run "${OV[@]}" new --name x --elf "$TMP/nope" --replace 0x00100000=f --out "$TMP/m.h"
eq "$ERR" "override: error: ELF not found: $TMP/nope" "ELF checked before the output"

# ---- slugs, default output, C strings
mkdir w && cd w || exit 1
run "${OV[@]}" new --name "Moon jump" --elf ../SLUS_999.99 --wrap 0x00100000=moon
eq "$CODE" 0 "default out"; eq "$(echo "$OUT" | head -1)" "wrote console/patches/moon_jump.cpp  (keys: SLUS_999.99, entry 0x00100000, CRC-32 0x${CRC})" "relative default path"
[ -f console/patches/moon_jump.cpp ] && [ -f console/patches/console_mods.cmake ] && ok || bad "default files"
run "${OV[@]}" new --name "Gold rifle!" --elf ../SLUS_999.99 --wrap 0x00100000=g; [ -f console/patches/gold_rifle.cpp ] && ok || bad "slug gold_rifle"
run "${OV[@]}" new --name "2 games in 1" --elf ../SLUS_999.99 --wrap 0x00100000=g; [ -f console/patches/m_2_games_in_1.cpp ] && ok || bad "slug m_2_games_in_1"
run "${OV[@]}" new --name "***" --elf ../SLUS_999.99 --wrap 0x00100000=g; [ -f console/patches/mod.cpp ] && ok || bad "slug mod"
run "${OV[@]}" new --name "Ünïcode Mod" --elf ../SLUS_999.99 --wrap 0x00100000=g; [ -f console/patches/n_code_mod.cpp ] && ok || bad "slug drops non-ASCII"
run "${OV[@]}" new --name 'a"b\c' --elf ../SLUS_999.99 --replace 0x00100000=g --out q.cpp
has "$(cat q.cpp)" 'PS2_REGISTER_GAME_OVERRIDE("a\"b\\c", "SLUS_999.99"' "c_string in the keys"
has "$(cat q.cpp)" 'std::cerr << "[console-mod] a\"b\\c: cannot replace' "c_string in the log line"
has "$(cat q.cpp)" "// Mod: a\"b\\c" "notes keep the raw name"
compiles q.cpp "escaped name compiles"
run "${OV[@]}" new --name "@FOO@ mod" --elf ../SLUS_999.99 --replace 0x00100000=g --out r.cpp
eq "$CODE" 2 "leftover field"; eq "$ERR" "override: error: template still has unfilled fields: @FOO@" "leftover field message"
cd "$TMP" || exit 1

# ---- templates: plain names, the library's .txt copies, missing
mkdir -p sk/templates; cp "$LIBSKILL/templates/override.cpp.txt" sk/templates/override.cpp
run --skill-dir "$TMP/sk" console-mod/override new --name t --elf SLUS_999.99 --replace 0x00100000=f --out "$TMP/t/t.cpp"
eq "$CODE" 2 "cmake template missing"
eq "$ERR" "override: error: templates/console_mods.cmake is missing (reinstall the console-mod skill)" "cmake missing message"
[ -f t/t.cpp ] && ok || bad "the module is written before the cmake check"
cp "$LIBSKILL/templates/console_mods.cmake.txt" sk/templates/console_mods.cmake
run --skill-dir "$TMP/sk" console-mod/override new --name t --elf SLUS_999.99 --replace 0x00100000=f --out "$TMP/t/t.cpp" --force
eq "$CODE" 0 "plain template names"
run --skill-dir "$TMP/nowhere" console-mod/override new --name t --elf SLUS_999.99 --replace 0x00100000=f --out "$TMP/t/u.cpp"
eq "$ERR" "override: error: templates/override.cpp is missing (reinstall the console-mod skill)" "template missing"
[ -e t/u.cpp ] && bad "nothing written without a template" || ok

# ---- help
run "${OV[@]}" --help
eq "$CODE" 0 "help exit"; has "$OUT" "new" "help new"; has "$OUT" "keys" "help keys"; has "$OUT" "Exit codes: 0 ok, 1 written with warnings, 2 bad input." "epilog"
run "${OV[@]}" new --help; eq "$CODE" 0 "new help"; has "$OUT" "usage:" "new usage"; has "$OUT" "--bind 0xADDR=handler" "bind metavar"
run "${OV[@]}" keys --help; has "$OUT" "usage:" "keys usage"
run "${OV[@]}"; eq "$CODE" 2 "no command"; has "$OUT" "usage:" "no command prints help"
run "${OV[@]}" new --elf SLUS_999.99; eq "$CODE" 2 "--name required"
done_ "console-mod/override"
